"""Generate the browser token stylesheet from docs/design-tokens.json."""

from __future__ import annotations

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "docs" / "design-tokens.json"
OUTPUT = ROOT / "app" / "static" / "tokens.css"


def load_tokens() -> dict:
    with SOURCE.open(encoding="utf-8") as handle:
        tokens = json.load(handle)
    colors = tokens.get("colors")
    if not isinstance(colors, dict) or set(colors) != {"light", "dark"}:
        raise ValueError("colors must contain light and dark themes")
    required = {"background", "surface", "surface-soft", "text", "secondary", "accent", "text-on-accent", "accent-soft", "divider"}
    for theme, values in colors.items():
        if set(values) != required:
            raise ValueError(f"{theme} colors must contain exactly {sorted(required)}")
        for name, value in values.items():
            if not isinstance(value, str) or len(value) != 7 or not value.startswith("#"):
                raise ValueError(f"{theme}.{name} must be a six-digit hex color")
    if set(tokens.get("spacing", {})) != {"1", "2", "3", "4", "5", "6", "7"}:
        raise ValueError("spacing must define 1 through 7")
    if set(tokens.get("radii", {})) != {"control", "card"}:
        raise ValueError("radii must define control and card")
    return tokens


def css(tokens: dict) -> str:
    lines = [
        "/* Generated by dev/generate_tokens.py; edit docs/design-tokens.json instead. */",
        ":root {",
        "  color-scheme: light;",
    ]
    for name, value in tokens["colors"]["light"].items():
        lines.append(f"  --{name}: {value};")
    for name, value in tokens["spacing"].items():
        lines.append(f"  --space-{name}: {value};")
    for name, value in tokens["radii"].items():
        lines.append(f"  --radius-{name}: {value};")
    lines += ["}", "", "@media (prefers-color-scheme: dark) {", "  :root {", "    color-scheme: dark;"]
    for name, value in tokens["colors"]["dark"].items():
        lines.append(f"    --{name}: {value};")
    lines += ["  }", "}", ""]
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="fail if the generated stylesheet is stale")
    args = parser.parse_args()
    generated = css(load_tokens())
    current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else None
    if args.check:
        if current != generated:
            print(f"{OUTPUT} is stale; run python dev/generate_tokens.py")
            return 1
        return 0
    OUTPUT.write_text(generated, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
